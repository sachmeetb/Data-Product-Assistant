"""DQ test package assembly — downloadable packages for generated DQ test suites.

Mirrors the serving_package pattern: collect_dq_files() gathers the generated
test code (excluding per-run results/), assemble_dq_package() adds a README,
and the result is a {rel_path: text} map ready for zip_response().
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from .config import BASE_PROJECT_DIR
from .dq_test_executor import _FRAMEWORKS, dq_subdir

_SOURCE_MODES = ("catalog", "dprod")

_EXCLUDE_DIRS = {"results", "__pycache__", ".venv"}
_EXCLUDE_NAMES = {".env"}


# ── Per-framework README templates ────────────────────────────────────────────

def _readme_gx(project_code: str) -> str:
    return f"""\
# DQ Tests — Great Expectations ({project_code})

> A self-contained, runnable [Great Expectations](https://greatexpectations.io/) test
> suite generated by Data Workbench from the **approved quality rules** for
> **{project_code}**. Every expectation traces back to one rule on the knowledge graph.
> This is the same package Data Workbench runs when you click **Run DQ Tests** — download
> it, point it at your database, and run it anywhere (CI included) with no Workbench
> dependency.

## Artifact inventory

| File / dir | Purpose |
|---|---|
| `run_gx_validations.py` | **Entry point — this is what you run.** Builds the expectation suites, validates each table, and writes the results. |
| `requirements.txt` | Python deps (`great-expectations` + your database driver). |
| `expectations/` *(generated)* | The expectation-suite definitions — one suite per table, each expectation derived from an approved rule. |
| `README.md` | This document. |
| `results/` *(created on run)* | Per-run outputs — see [Outputs](#outputs). Excluded from the package until you run it. |

## How it works

```mermaid
flowchart LR
    R["Approved quality rules<br/>(knowledge graph)"] -->|generated once| S["expectations/<br/>(one suite per table)"]
    ENV["--conn-string / flags"] --> V["run_gx_validations.py"]
    S --> V
    V -->|validate each table| DB[("Your database<br/>tables or vw_* views")]
    V --> OUT["results/<br/>run_result.json + report.md"]
    style R fill:#eef2ff,stroke:#6366f1
    style OUT fill:#f0fdf4,stroke:#16a34a
```

## How the technology works

Great Expectations models data quality as **expectation suites** — named collections of
declarative checks (`expect_column_values_to_not_be_null`,
`expect_column_values_to_be_between`, `expect_column_values_to_be_in_set`, …). Data
Workbench compiles each **approved rule** into exactly one expectation, groups the
expectations by table into a suite, and the runner validates each table's suite against
live data using a SQL-backed datasource (no data is copied — GX pushes the checks down as
SQL). Each expectation's result carries the count and a sample of the *unexpected* values,
so a failure tells you not just **that** a rule broke but **which rows** broke it.

```mermaid
flowchart TD
    subgraph "per table"
      C["connect (SQLAlchemy)"] --> Q["run the table's<br/>expectation suite"]
      Q --> A{"all expectations<br/>pass?"}
      A -->|yes| P["record PASS"]
      A -->|no| F["record FAIL<br/>+ unexpected samples"]
    end
    P --> RR["aggregate → run_result.json + report.md"]
    F --> RR
    RR --> X{"any table failed?"}
    X -->|yes| NZ["exit non-zero (CI gate)"]
    X -->|no| Z["exit 0"]
    style F fill:#fef2f2,stroke:#dc2626
    style Z fill:#f0fdf4,stroke:#16a34a
```

## Configuration

| Flag / env | Required | Description |
|---|---|---|
| `--conn-string` | yes | SQLAlchemy connection string for the database to test (e.g. `postgresql://user:pass@host:5432/db`). |
| `--sample-limit` | no | Cap rows scanned per table (faster smoke run). Omit to validate the full table. |
| `--output-dir` | no | Where to write `results/` (default `results/`). |

Secrets ride the process/CLI only — nothing is written to disk beyond the results you ask for.

## Usage

```bash
pip install -r requirements.txt
python run_gx_validations.py --conn-string "<your-connection-string>"
# full data by default; add --sample-limit 5000 for a quick smoke run
python run_gx_validations.py --conn-string "<...>" --sample-limit 5000
```

The process **exits non-zero when any expectation fails**, so it drops straight into a CI gate.

## Outputs

Every run writes three files into the output directory (`results/` by default):

| File | Purpose |
|---|---|
| `run_result.json` | **Machine-readable verdict** (the v1 `run_result.json` contract shared with the serving packages): `status` (`success`/`failed`), per-table `steps`, and `metrics` (tables, expectations passed/failed, `tables_failed`). Parse this in CI. |
| `report.md` | **Human-readable report**: overall PASS/FAIL, a per-table pass/fail table, and each failed expectation with its unexpected sample values. |
| `gx_results_<timestamp>.json` | The full framework-native GX result log (kept per-run for history). |

### Load results back into Data Workbench

Re-run the **Run DQ Tests** stage from the UI or via the MCP `run_stage` tool — it
re-executes the suite and loads the latest results back into the graph automatically.
"""


