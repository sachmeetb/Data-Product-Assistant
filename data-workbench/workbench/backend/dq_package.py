_README_BUILDERS = {
    "gx": _readme_gx,
    "pandera": _readme_python,
}


# ── Detection + collection ────────────────────────────────────────────────────

def detect_active_framework(project_code: str, source_mode: str = "catalog") -> Optional[str]:
    """Return the active DQ framework name ('gx' or 'pandera') by checking which
    generated entry-point script exists on disk for the given ``source_mode``
    (catalog → ``dq_tests_*``; dprod → ``dq_tests_*_dprod``). Returns None when no
    test suite has been generated yet for that mode."""
    project_dir = BASE_PROJECT_DIR / project_code
    for fw in _FRAMEWORKS:
        script = project_dir / dq_subdir(fw["subdir"], source_mode) / fw["script"]
        if script.exists():
            return fw["framework"]
    return None


def available_dq_suites(project_code: str) -> list[dict]:
    """Enumerate the generated DQ suites present on disk, across both modes.

    Returns a list of ``{"framework", "source_mode"}`` for every framework whose
    entry-point script exists. A `dpe-sa` product can hold both a catalog and a
    dprod suite; a `dpe-cf` product only ever has the dprod one. dprod is listed
    first so callers that need a single default treat the product suite as primary.
    """
    project_dir = BASE_PROJECT_DIR / project_code
    suites: list[dict] = []
    for mode in ("dprod", "catalog"):
        for fw in _FRAMEWORKS:
            script = project_dir / dq_subdir(fw["subdir"], mode) / fw["script"]
            if script.exists():
                suites.append({"framework": fw["framework"], "source_mode": mode})
    return suites


def resolve_suite(project_code: str, source_mode: Optional[str] = None) -> tuple[Optional[str], Optional[str]]:
    """Pick a (framework, source_mode) suite for a reader/download.

    Honors an explicit ``source_mode`` when that suite exists; otherwise falls back
    to whatever is present (dprod preferred — the product suite is primary). Returns
    ``(None, None)`` when nothing has been generated yet.
    """
    suites = available_dq_suites(project_code)
    if not suites:
        return None, None
    if source_mode:
        match = next((s for s in suites if s["source_mode"] == source_mode), None)
        if match:
            return match["framework"], match["source_mode"]
    chosen = suites[0]  # available_dq_suites lists dprod first
    return chosen["framework"], chosen["source_mode"]


def collect_dq_files(
    project_code: str,
    framework: Optional[str] = None,
    source_mode: str = "catalog",
) -> dict[str, str]:
    """Collect generated DQ test files into a {rel_path: text} map.

    Excludes ``results/`` (per-run output) and cache dirs. Returns an empty dict
    when no test files exist yet. ``framework`` defaults to auto-detection from disk
    within the given ``source_mode``'s subdir.
    """
    if framework is None:
        framework = detect_active_framework(project_code, source_mode)
    if framework is None:
        return {}

    fw_meta = next((f for f in _FRAMEWORKS if f["framework"] == framework), None)
    if fw_meta is None:
        return {}

    test_dir = BASE_PROJECT_DIR / project_code / dq_subdir(fw_meta["subdir"], source_mode)
    if not test_dir.exists():
        return {}

    files: dict[str, str] = {}
    for p in sorted(test_dir.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(test_dir)
        if any(part in _EXCLUDE_DIRS for part in rel.parts):
            continue
        if p.name in _EXCLUDE_NAMES:
            continue
        try:
            files[str(rel)] = p.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            pass  # skip unreadable / binary files silently
    return files


def assemble_dq_package(
    project_code: str,
    framework: Optional[str] = None,
    source_mode: str = "catalog",
) -> Optional[dict[str, str]]:
    """Assemble a downloadable DQ test package: test files + README.

    Returns None when no generated test files exist yet.
    Returns a {rel_path: text} map for use with serving_package.zip_response().
    """
    if framework is None:
        framework = detect_active_framework(project_code, source_mode)
    if framework is None:
        return None

    files = collect_dq_files(project_code, framework, source_mode)
    if not files:
        return None

    readme_builder = _README_BUILDERS.get(framework)
    if readme_builder and "README.md" not in files:
        readme = readme_builder(project_code)
        if source_mode == "dprod":
            readme += (
                "\n> **Product (dprod) suite** — these tests validate the "
                "**deployed product views** (`vw_*`) against the rules authored on "
                "the data contract (`:DProdColumn`), not the raw source tables. "
                "Point `--conn-string` at the deployed product target.\n"
            )
        files["README.md"] = readme

    return files
